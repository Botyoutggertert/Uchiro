export interface KHQROptions {
  merchantName?: string;
  merchantCity?: string;
  bakongAccountId?: string;
  amount: number;
  currency?: 'USD' | 'KHR';
  billNumber?: string;
  storeLabel?: string;
  terminalLabel?: string;
}

export function generateKHQRPayload(options: KHQROptions): string {
  const {
    merchantName = 'UCHIRO STORE',
    merchantCity = 'Phnom Penh',
    bakongAccountId = 'khinsovan_noreakyout@bkrt',
    amount,
    currency = 'USD',
    billNumber = `ORD-${Math.floor(1000 + Math.random() * 9000)}`,
    storeLabel = 'Uchiro Market',
    terminalLabel = 'POS-01',
  } = options;

  const isUSD = currency.toUpperCase() === 'USD';
  const minAmt = isUSD ? 0.01 : 100;
  const rawAmt = Number(amount);
  const validAmt = Math.max(minAmt, isNaN(rawAmt) ? minAmt : rawAmt);
  const formattedAmount = isUSD ? validAmt.toFixed(2) : Math.round(validAmt).toString();
  const currencyCode = isUSD ? '840' : '116';
  const now = Date.now();
  const expiry = now + 24 * 60 * 60 * 1000;

  // Sub-tags for Tag 29 (Merchant Account Information - Bakong Individual Standard)
  const tag29Value = formatTLV('00', bakongAccountId.trim());

  // Sub-tags for Tag 62 (Additional Data Field Template)
  let tag62Value = '';
  if (billNumber) tag62Value += formatTLV('01', billNumber.trim());
  if (storeLabel) tag62Value += formatTLV('03', storeLabel.trim());
  if (terminalLabel) tag62Value += formatTLV('07', terminalLabel.trim());

  // Sub-tags for Tag 99 (Dynamic QR Timestamps)
  const tag99Value = `${formatTLV('00', now.toString())}${formatTLV('01', expiry.toString())}`;

  let payload = '';
  payload += formatTLV('00', '01'); // Payload Format Indicator
  payload += formatTLV('01', '12'); // Dynamic QR Point of Initiation (12 for Dynamic, 11 for Static)
  payload += formatTLV('29', tag29Value); // Merchant Account Information (Bakong)
  payload += formatTLV('52', '5999'); // Merchant Category Code (Digital Goods / Gaming)
  payload += formatTLV('53', currencyCode); // Transaction Currency (840 = USD, 116 = KHR)
  payload += formatTLV('54', formattedAmount); // Transaction Amount
  payload += formatTLV('58', 'KH'); // Country Code (Cambodia)
  payload += formatTLV('59', merchantName.trim().slice(0, 25)); // Merchant Name
  payload += formatTLV('60', merchantCity.trim().slice(0, 15)); // Merchant City
  if (tag62Value) payload += formatTLV('62', tag62Value); // Additional Data Field
  payload += formatTLV('99', tag99Value); // Dynamic Timestamps

  // Add Tag 63 with length 04 and calculate CRC
  const payloadToCrc = `${payload}6304`;
  const crc = calculateCRC16(payloadToCrc);
  return `${payloadToCrc}${crc}`;
}

export function generateBakongDeepLink(qrString: string): string {
  const encoded = encodeURIComponent(qrString);
  return `https://bakong.nbc.gov.kh/qr/${encoded}`;
}

export async function generateQRCodeDataURL(text: string): Promise<string> {
  try {
    const dataUrl = await QRCode.toDataURL(text, {
      errorCorrectionLevel: 'M',
      margin: 2,
      width: 400,
      color: {
        dark: '#000000',
        light: '#FFFFFF',
      },
    });
    return dataUrl;
  } catch (err) {
    console.error('Failed to generate QR code:', err);
    return '';
  }
}

export async function generateKHQRDataURL(optionsOrText: KHQROptions | string): Promise<string> {
  const payload = typeof optionsOrText === 'string' ? optionsOrText : generateKHQRPayload(optionsOrText);
  return generateQRCodeDataURL(payload);
}
